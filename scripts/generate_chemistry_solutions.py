def format_to_oled(content):
    """Format full text into strict 32-character line OLED format."""
    blocks = re.split(r'(QUESTION \d+:)', content)
    output_lines = []

    # Process preamble (Header of paper)
    preamble = blocks[0]
    for line in preamble.split('\n'):
        line_s = line.strip()
        if not line_s:
            output_lines.append("")
        elif set(line_s) == {'='} or set(line_s) == {'-'}:
            output_lines.append(line_s[0] * 32)
        else:
            wrapped = textwrap.wrap(line_s, width=32, break_long_words=True, break_on_hyphens=False)
            output_lines.extend(wrapped)

    for i in range(1, len(blocks), 2):
        q_tag = blocks[i].strip()  # "QUESTION N:"
        q_body = blocks[i+1] if (i+1) < len(blocks) else ""

        q_num_match = re.search(r'QUESTION (\d+):', q_tag)
        q_num = q_num_match.group(1) if q_num_match else str(i)

        output_lines.append("")
        output_lines.append("=" * 32)
        output_lines.append(f"QUESTION {q_num}".center(32))
        output_lines.append("=" * 32)
        output_lines.append("")

        for b_line in q_body.split('\n'):
            b_s = b_line.strip()
            if not b_s:
                output_lines.append("")
            elif set(b_s) == {'='} or set(b_s) == {'-'}:
                output_lines.append("-" * 32)
            else:
                indent_len = len(b_line) - len(b_line.lstrip())
                indent_str = " " * min(indent_len, 4)
                wrapped = textwrap.wrap(b_s, width=max(10, 32 - len(indent_str)), break_long_words=True, break_on_hyphens=False)
                for w in wrapped:
                    output_lines.append(indent_str + w)

        end_tag = f"[ END OF QUESTION {q_num} ]"
        output_lines.append("")
        output_lines.append("-" * 32)
        output_lines.append(end_tag.center(32))
        output_lines.append("-" * 32)
        output_lines.append("")

    full_oled = '\n'.join(output_lines)
    full_oled_single_gap = re.sub(r'\n{3,}', '\n\n', full_oled)

    # Verification
    final_lines = full_oled_single_gap.split('\n')
    err_count = sum(1 for l in final_lines if len(l) > 32)
    print(f"OLED Lines: {len(final_lines)}, Max Len: {max(len(l) for l in final_lines)}, Errors >32: {err_count}")

    return full_oled_single_gap

